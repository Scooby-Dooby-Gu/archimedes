export function getEffect(event) {
  var effect = 0;
  for (var property in event.effects) {
    if (property === 'stocks') {
      effect += event.effects[property] * 10;
    } else if (property === 'property') {
      effect += event.effects[property] / 3;
    } else if (property === 'rfr') {
      effect += event.effects[property] / 0.0025;
    } else if (property === 'rfrReset') {
      effect -= 4;
    } else {
      effect += event.effects[property] * 10 / 6;
    }
  }
  return effect;
}

