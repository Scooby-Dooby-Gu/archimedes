CREATE OR REPLACE FUNCTION public.assign_lesson_achievements()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
DECLARE
   passed_lesson_count integer;
   passed_course_count integer;
   user_company_id integer;
   best_user_id integer;
BEGIN
  SELECT count(*) FROM submissions WHERE user_id=new.user_id and is_complete and type='lesson' INTO passed_lesson_count;
  IF passed_lesson_count = 1 THEN  
    INSERT INTO user_achievements(user_id, achievement_id) VALUES(new.user_id, (SELECT id FROM achievements where slug='lesson_1')) ON CONFLICT DO NOTHING;
  END IF;
  IF passed_lesson_count = 5 THEN
    INSERT INTO user_achievements(user_id, achievement_id) VALUES(new.user_id, (SELECT id FROM achievements where slug='lesson_2')) ON CONFLICT DO NOTHING;
  END IF;
  IF passed_lesson_count = 20 THEN
    INSERT INTO user_achievements(user_id, achievement_id) VALUES(new.user_id, (SELECT id FROM achievements where slug='lesson_3')) ON CONFLICT DO NOTHING;
  END IF;

  SELECT company_id FROM users where id = new.user_id INTO user_company_id;
  IF user_company_id IS NOT NULL THEN
    SELECT user_id
      FROM submissions 
      INNER JOIN users on submissions.user_id = users.id 
      WHERE is_complete and type='lesson'
      GROUP BY 1 
      ORDER BY count(*) DESC
      LIMIT 1
      INTO best_user_id;
    IF new.user_id = best_user_id THEN
      DELETE FROM user_achievements
        WHERE company_id = user_company_id
        AND user_id != new.user_id
        AND achievement_id = (SELECT id FROM achievements where slug='most_educated_in_company');

      INSERT INTO user_achievements(user_id, achievement_id, company_id) VALUES(
        new.user_id, 
        (SELECT id FROM achievements where slug='most_educated_in_company'), 
        user_company_id) ON CONFLICT DO NOTHING;
    END IF;
  END IF;

  SELECT count(*)
  FROM courses
  JOIN LATERAL (
    SELECT count(*) FROM lessons
    INNER JOIN submissions ON submissions.lesson_id = lessons.id
    WHERE lessons.course_id = courses.id
    AND submissions.user_id = new.user_id
    AND submissions.is_complete
  ) s ON TRUE
  WHERE courses.lesson_count = s.count
  INTO passed_course_count;

  IF passed_course_count = 1 THEN  
    INSERT INTO user_achievements(user_id, achievement_id) VALUES(new.user_id, (SELECT id FROM achievements where slug='course_1')) ON CONFLICT DO NOTHING;
  END IF;
  IF passed_course_count = 5 THEN
    INSERT INTO user_achievements(user_id, achievement_id) VALUES(new.user_id, (SELECT id FROM achievements where slug='course_2')) ON CONFLICT DO NOTHING;
  END IF;

  RETURN NULL;
END;
$function$
