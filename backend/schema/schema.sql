CREATE OR REPLACE FUNCTION update_related_users()
  RETURNS trigger AS
$BODY$
DECLARE
  user_id integer;
  related_ids integer[];
BEGIN
  SELECT CASE WHEN TG_OP = 'DELETE' THEN old.source_id ELSE new.source_id END INTO user_id;

  -- compute friends of friends list
  SELECT compute_related_users(user_id) INTO related_ids;

  -- update users
  UPDATE private.users SET related_user_ids = compute_related_users(id) WHERE id = ANY(related_ids) OR id = user_id;
  
  -- propagate verification
  IF ARRAY_LENGTH(related_ids, 1) >= 3 
     OR EXISTS(SELECT 1 
               FROM private.users
               WHERE verified_at is not NULL
               AND id = ANY(related_ids)) THEN
    UPDATE private.users 
      SET verified_at = NOW()
      WHERE id = ANY(related_ids) 
        AND verified_at is NULL;
  END IF;
  
  RETURN NULL;
END;
$BODY$
LANGUAGE plpgsql;


CREATE TRIGGER update_related_users_trigger
AFTER INSERT OR DELETE ON friendships
FOR EACH ROW EXECUTE PROCEDURE update_related_users();



DROP AGGREGATE IF EXISTS array_cat_agg(anyarray);
CREATE AGGREGATE array_cat_agg(anyarray) (
  SFUNC=array_cat,
  STYPE=anyarray
);


CREATE OR REPLACE FUNCTION random_between(low INT ,high INT) 
   RETURNS INT AS
$$
BEGIN
   RETURN floor(random()* (high-low + 1) + low);
END;
$$ language 'plpgsql' STRICT;


