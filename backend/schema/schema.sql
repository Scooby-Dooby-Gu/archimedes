CREATE OR REPLACE FUNCTION update_total_reply_count_trigger()
  RETURNS trigger AS
$BODY$
DECLARE
   _id int;
BEGIN
   CASE TG_OP
      WHEN 'INSERT', 'UPDATE' THEN
         _id := NEW.discussion_id;
      WHEN 'DELETE' THEN
         _id := OLD.discussion_id;
   END CASE;

   UPDATE discussions SET reply_count = (
     SELECT count(*) 
     FROM replies 
     WHERE discussion_id = _id
   ), last_reply_at = NOW()
   WHERE id = _id;

   RETURN NULL;
END
$BODY$
LANGUAGE plpgsql;



