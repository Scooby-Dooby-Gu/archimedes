CREATE OR REPLACE FUNCTION update_discussion_search_vector()
  RETURNS trigger AS
$BODY$
BEGIN
    WITH person as (SELECT * from private.users where id = new.user_id),
       topic as (SELECT * from topics where id = new.topic_id),
       board as (SELECT boards.* from boards, topic where boards.id = topic.board_id)
   SELECT setweight(to_tsvector('english', coalesce(new.name, '')), 'A') || 
          setweight(to_tsvector('english', coalesce(new.description, '')), 'B') || 
          setweight(to_tsvector('english', coalesce(person.name, '')), 'C') || 
          setweight(to_tsvector('english', coalesce(topic.name, '')), 'C') || 
          setweight(to_tsvector('english', coalesce(topic.description, '')), 'D') || 
          setweight(to_tsvector('english', coalesce(board.name, '')), 'C') || 
          setweight(to_tsvector('english', coalesce(board.description, '')), 'D')
   FROM person, topic, board
   into new.search;

   RETURN NEW;
END;
$BODY$
LANGUAGE plpgsql;

