CREATE OR REPLACE FUNCTION trigger_set_updated_at_timestamp()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER update_lesson_timestamp_trigger
BEFORE UPDATE ON lessons
FOR EACH ROW
EXECUTE PROCEDURE trigger_set_updated_at_timestamp();


CREATE TRIGGER update_discussion_timestamp_trigger
BEFORE UPDATE ON discussions
FOR EACH ROW
EXECUTE PROCEDURE trigger_set_updated_at_timestamp();